import { execFileSync } from 'node:child_process'
import { lstatSync, writeFileSync } from 'node:fs'
import { dirname, isAbsolute, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const STAGING_ENV_ID = 'sbhmini-d5g7d6732b2c64a66'
const STAGING_SERVICE_NAME = 'sbhmini'
const shaPattern = /^[0-9a-f]{40}$/
const revisionPattern = /^[A-Za-z0-9._-]{1,128}$/

export function prepareTrialDeployment({ environment, currentHeadSha, worktreeStatus, outputPath, allowedOutputPath }) {
  const env = environment ?? process.env
  const cloudEnvId = env.TRIAL_CLOUD_ENV_ID ?? ''
  const cloudServiceName = env.TRIAL_CLOUD_SERVICE_NAME ?? ''
  if (cloudEnvId !== STAGING_ENV_ID) throw new Error('trial cloud env 与受控 staging 不一致')
  if (cloudServiceName !== STAGING_SERVICE_NAME) throw new Error('trial cloud service 与受控 staging 不一致')
  const targetSha = env.TRIAL_DEPLOYMENT_COMMIT_SHA ?? ''
  if (!shaPattern.test(targetSha) || targetSha !== currentHeadSha) throw new Error('目标 Git commit SHA 与当前 HEAD 不一致')
  const revision = env.TRIAL_SERVER_DEPLOYMENT_REVISION ?? ''
  if (!revisionPattern.test(revision)) throw new Error('缺少或非法服务端 deployment revision')
  if (worktreeStatus !== '') throw new Error('工作树必须干净后才能生成 trial manifest')
  if (!outputPath || !isAbsolute(outputPath)) throw new Error('必须显式提供绝对输出路径')
  if (!allowedOutputPath || resolve(outputPath) !== resolve(allowedOutputPath)) throw new Error('输出路径不在允许的 trial manifest 位置')
  try {
    if (lstatSync(outputPath).isSymbolicLink()) throw new Error('输出路径不能是符号链接')
  } catch (error) {
    if (error instanceof Error && error.message === '输出路径不能是符号链接') throw error
    if (error?.code !== 'ENOENT') throw error
  }
  const manifest = {
    cloudEnvId,
    cloudServiceName,
    gitCommitSha: targetSha,
    serverDeploymentRevision: revision,
  }
  const source = `// generated by prepare-trial-deployment; do not edit\nexport const trialDeploymentManifest = Object.freeze(${JSON.stringify(manifest)} as const)\n`
  writeFileSync(outputPath, source, { encoding: 'utf8', flag: 'w' })
  return source
}

export function main() {
  try {
    const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
    const currentHeadSha = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: projectRoot, encoding: 'utf8' }).trim()
    const worktreeStatus = execFileSync('git', ['status', '--porcelain', '--untracked-files=all'], { cwd: projectRoot, encoding: 'utf8' })
    prepareTrialDeployment({ environment: process.env, currentHeadSha, worktreeStatus, outputPath: process.env.TRIAL_DEPLOYMENT_OUTPUT_PATH, allowedOutputPath: resolve(projectRoot, 'miniprogram/config/trial-deployment.generated.ts') })
    console.log('trial deployment manifest 已生成')
  } catch (error) {
    console.error(`trial deployment manifest 生成失败：${error instanceof Error ? error.message : '未知错误'}`)
    process.exitCode = 1
  }
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) main()
